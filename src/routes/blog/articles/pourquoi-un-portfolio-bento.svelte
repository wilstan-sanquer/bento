    <h1>Pourquoi j'ai choisi le format Bento</h1>
    <p class="date">Publié le 26 juillet 2026</p>

    <p>Pour mon portfolio, j'ai choisi un format bento plutôt qu'une mise en page plus classique. Ce choix ne doit rien au hasard : voici pourquoi.</p>

    <h2>1. Qu'est-ce que le format bento ?</h2>
    <p>Le format bento, c'est une mise en page composée de blocs de tailles différentes, assemblés comme dans une grille, un peu à l'image des boîtes bento japonaises qui rangent plusieurs compartiments dans un même plateau.</p>
    <p>Chaque bloc met en avant une information précise : une compétence, un projet, un lien social... Ce format est devenu une vraie tendance ces dernières années dans les portfolios de développeurs et designers, notamment parce qu'il permet de présenter beaucoup d'informations de façon claire et visuellement organisée.</p>

    <h2>2. Pourquoi ce choix pour mon portfolio ?</h2>
    <p>Avant d'arriver au bento, j'avais déjà essayé plusieurs fois de développer mon portfolio en page simple, mais je n'arrivais jamais à organiser correctement mes sections.</p>
    <p>Tout semblait soit trop dense, soit mal structuré. En découvrant le format bento, ce style m'a tout de suite intéressé : il apportait exactement la structure claire qui me manquait, avec un espace bien défini pour chaque information.</p>
