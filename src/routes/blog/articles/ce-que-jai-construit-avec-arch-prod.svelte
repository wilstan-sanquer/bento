    <h1>Ce que j'ai construit avec Arch-Prod.</h1>
    <p class="date">Publié le 26 juillet 2026</p>

    <p>Arch-Prod est un studio de développement web & logiciel que j'ai co-fondé avec Jean Chevrier en parallèle de nos études.</p>
    <p>Ce studio est né d'une envie simple : développer des programmes et des sites web pour aider les entreprises à avoir une présence sur internet, tout en nous faisant progresser.</p>

    <h2>1. Pourquoi créer un studio plutôt qu'attendre un stage/alternance.</h2>
    <p>En tant qu'étudiants, une grande partie de nos connaissances restait théorique, et les programmes développés en cours pour nous faire travailler une notion ne nous motivaient plus. Nous voulions utiliser nos compétences dans des projets qui nous apportent de la satisfaction.</p>
    <p>Les projets scolaires suivent souvent un cadre imposé, avec des consignes précises et peu de place pour nos propres idées. On voulait sortir de ce format pour créer des choses qui nous ressemblent, avec une vraie liberté de choix techniques et créatifs.</p>
    <p>C'est de ce constat qu'est née l'idée d'Arch-Prod : plutôt que de rester sur des exercices théoriques, pourquoi ne pas mettre nos compétences au service de vrais projets, avec de vrais enjeux et de vraies personnes en face ?</p>

    <h2>2. La naissance d'Arch-Prod avec Jean.</h2>
    <p>C'est de cette envie commune qu'est né Arch-Prod. Avec Jean, on partageait le même constat, alors on a décidé de se lancer ensemble plutôt que d'attendre chacun de notre côté. On a réparti nos rôles selon nos forces : moi sur le développement frontend et Java, lui sur le développement d'outils réseau et la cybersécurité.</p>

    <h2>3. Ce qu'Arch-Prod m'apporte.</h2>
    <p>Arch-Prod m'apporte bien plus qu'un simple projet à ajouter à mon CV. C'est une expérience professionnelle complète, avec de vrais clients, de vraies contraintes et de vraies responsabilités.</p>
    <p> Chaque projet me pousse à progresser techniquement, que ce soit en frontend ou en Java, tout en apprenant à collaborer efficacement avec Jean sur des enjeux concrets.</p>
    <p>C'est cette expérience de terrain qui, je pense, fera la différence dans ma recherche d'alternance, et qui me rapproche chaque jour un peu plus de mon objectif : devenir Développeur Full-Stack.</p>
